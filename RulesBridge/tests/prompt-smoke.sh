#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
: "${XMAGE_HOME:?Set XMAGE_HOME to the extracted xmage directory}"
: "${RULES_BRIDGE_TOKEN:?Set the bridge connection key}"
mkdir -p build/test-classes
rules_test_classpath="build/test-classes:build/magicboard-rules.jar:lib/*:$XMAGE_HOME/mage-client/lib/*"
javac --release 17 -cp "$rules_test_classpath" -d build/test-classes tests/BridgeSmoke.java
unset RULES_SMOKE_ABILITY RULES_SMOKE_DECK RULES_SMOKE_COVERAGE_ONLY RULES_SMOKE_REQUIRED_PROMPTS RULES_SMOKE_MANUAL_TRIGGERS RULES_SMOKE_SPECIAL_ACTION RULES_SMOKE_RESOLVE_STACK RULES_SMOKE_ACTIVATE RULES_SMOKE_FORCE_DISCARD RULES_SMOKE_RESPOND RULES_SMOKE_RECAST RULES_SMOKE_CANCEL_ONCE RULES_SMOKE_CANCEL_CHOICE
probe() {
    rules_scenario="$1"
    rules_required="$2"
    shift 2
    env RULES_SMOKE_DECK="tests/decks/$rules_scenario.json" RULES_SMOKE_COVERAGE_ONLY=1 \
        RULES_SMOKE_REQUIRED_PROMPTS="$rules_required" "$@" \
        java -Xmx256m -cp "$rules_test_classpath" BridgeSmoke
}
probe triggers GAME_TARGET/PICK_ABILITY RULES_SMOKE_MANUAL_TRIGGERS=1
probe modes GAME_CHOOSE_ABILITY,MODAL_SPELL_CAST
probe costs ALTERNATIVE_COST,ALTERNATIVE_SPELL_CAST
probe morph SPECIAL_ACTION,MORPH_REVEALED RULES_SMOKE_SPECIAL_ACTION=1
probe x-mana GAME_GET_AMOUNT,NONZERO_X_SPELL_CAST
probe hybrid HYBRID_SPELL_CAST
probe search LIBRARY_CARD_TO_HAND
probe hybrid STACK_RESOLVED_STOP RULES_SMOKE_RESOLVE_STACK=1
probe equip PERMANENT_ACTIVATED,EQUIPMENT_ATTACHED RULES_SMOKE_ACTIVATE=Bonesplitter
probe loyalty PERMANENT_ACTIVATED,LOYALTY_GAINED_LIFE 'RULES_SMOKE_ACTIVATE=Ajani Goldmane'
probe hybrid CLEANUP_CARD_DISCARDED RULES_SMOKE_FORCE_DISCARD=1
probe response OPPONENT_TURN_INSTANT_CAST,INSTANT_RESPONSE_GAINED_LIFE RULES_SMOKE_RESPOND=1
probe damage GAME_GET_MULTI_AMOUNT,DIVIDED_DAMAGE_SPELL_CAST,DIVIDED_DAMAGE_RESOLVED
probe piles GAME_CHOOSE_PILE,CHOSEN_PILE_TO_HAND
probe flashback GRAVEYARD_CAST_SELECTED,FLASHBACK_EXILED 'RULES_SMOKE_RECAST=Think Twice'
probe hybrid CANCELLED_CAST_RECOVERED RULES_SMOKE_CANCEL_ONCE=1
probe modes GAME_CHOOSE_ABILITY,CANCELLED_CAST_RECOVERED RULES_SMOKE_CANCEL_CHOICE=1

probe explore EXPLORE_QUESTION_HAS_CARD,EXPLORED_CARD_TO_GRAVEYARD

probe transform TRANSFORMED_DELVER_3_2

probe costed-mana COSTED_MANA_SPELL_CAST

probe vehicle PERMANENT_ACTIVATED,VEHICLE_CREWED_2_3 'RULES_SMOKE_ACTIVATE=Sky Skiff'
